// Generates TypeScript types and standalone validators from ../schema.
// Usage: node scripts/generate.mjs [--check]
// Standalone validators avoid runtime code generation (eval), which the
// browser extension's Manifest V3 content security policy forbids.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { Ajv } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../', import.meta.url);
const schemaDir = new URL('schema/', root);
const outDir = new URL('src/generated/', root);
const check = process.argv.includes('--check');

const banner =
  '// @generated by packages/contracts/scripts/generate.mjs from packages/contracts/schema.\n' +
  '// Do not edit by hand; run `pnpm contracts:generate`.\n';

/** @type {{ file: string, name: string, schema: Record<string, unknown> & { $id: string, title: string } }[]} */
const schemas = readdirSync(schemaDir)
  .filter((file) => file.endsWith('.schema.json'))
  .sort()
  .map((file) => {
    const schema = JSON.parse(readFileSync(new URL(file, schemaDir), 'utf8'));
    return { file, name: file.replace('.schema.json', ''), schema };
  });

/** @type {Map<string, string>} */
const outputs = new Map();

for (const { name, schema } of schemas) {
  const types = await compile(schema, schema.title, {
    bannerComment: banner,
    additionalProperties: false,
    style: { singleQuote: true, printWidth: 100 },
  });
  outputs.set(`${name}.ts`, types);
}

const ajv = new Ajv({ code: { source: true, esm: true }, strict: true });
addFormats(ajv, ['uuid']);
/** @type {Record<string, string>} */
const exportsById = {};
for (const { schema } of schemas) {
  ajv.addSchema(schema);
  exportsById[`validate${schema.title}`] = schema.$id;
}
// Ajv's ESM output still calls require() for its string-length helper. Inline
// an equivalent (counts Unicode code points) so the module is pure ESM with no
// runtime dependency on ajv.
const UCS2_REQUIRE = 'require("ajv/dist/runtime/ucs2length").default';
const ucs2length =
  'function ucs2length(str) {\n  let length = 0;\n  for (const _ of str) length++;\n  return length;\n}\n';
const validators = standaloneCode(ajv, exportsById).replaceAll(UCS2_REQUIRE, 'ucs2length');
if (/\brequire\(/.test(validators)) {
  console.error('Generated validators still contain require(); update scripts/generate.mjs.');
  process.exit(1);
}
outputs.set('validators.js', `${banner}// @ts-nocheck\n${ucs2length}${validators}\n`);
outputs.set(
  'validators.d.ts',
  `${banner}import type { ErrorObject } from 'ajv';\n\n` +
    'export interface StandaloneValidator {\n' +
    '  (data: unknown): boolean;\n' +
    '  errors?: ErrorObject[] | null;\n' +
    '}\n\n' +
    Object.keys(exportsById)
      .map((name) => `export declare const ${name}: StandaloneValidator;\n`)
      .join(''),
);

let stale = [];
for (const [file, content] of outputs) {
  const url = new URL(file, outDir);
  if (check) {
    let current = '';
    try {
      current = readFileSync(url, 'utf8');
    } catch {
      // Missing file counts as stale.
    }
    if (current !== content) stale.push(file);
  } else {
    writeFileSync(url, content);
  }
}

if (stale.length > 0) {
  console.error(
    `packages/contracts/src/generated is out of date (${stale.join(', ')}); run \`pnpm contracts:generate\`.`,
  );
  process.exit(1);
}
